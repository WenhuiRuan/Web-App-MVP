test('mock reconnect fills missed events once and discussion switch clears old content', async ({ page }) => {
  await page.goto(`/?mode=mock&pace=fast#/discussion/${firstId}`)
  await expect(page.getByText('模拟连接正常', { exact: true })).toBeVisible()
  await tool(page, '模拟当前连接中断')
  const count = await page.getByTestId('message').count()
  await expect(page.getByRole('button', { name: '重新连接', exact: true })).toBeVisible()
  await page.waitForTimeout(1500) // Deliberately accrue several events while this subscription is offline.
  await expect(page.getByTestId('message')).toHaveCount(count)
  await page.getByRole('button', { name: '重新连接', exact: true }).click()
  await expect.poll(() => page.getByTestId('message').count()).toBeGreaterThan(count)
  const ids = await page.getByTestId('message').evaluateAll(nodes => nodes.map(n => n.getAttribute('data-message-id')))
  expect(new Set(ids).size).toBe(ids.length)
  await page.getByLabel('切换讨论').selectOption(secondId)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('混合办公要如何保持协作与公平？')
  await expect(page.getByTestId('message').first()).toContainText('混合办公')
  const switched = await page.getByTestId('message').evaluateAll(nodes => nodes.map(n => n.getAttribute('data-message-id')))
  expect(switched.some(id => ids.includes(id))).toBeFalsy()
  await page.waitForTimeout(600)
  await expect(page.getByTestId('message').first()).toContainText('混合办公')
})

